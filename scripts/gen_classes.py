"""Generate src/game/classes.ts: the g.classes registry (Lingo _ClassDefinitions) of every exported class.

Usage (from the repo root): python -I scripts/gen_classes.py src/game
"""
import glob
import os
import re
import sys

game = sys.argv[1]
names = []  # (class name, import path relative to src/game)
for p in sorted(glob.glob(os.path.join(game, '**', '*.ts'), recursive=True), key=lambda p: os.path.basename(p)):
    base = os.path.basename(p)[:-3]
    if base in ('classes', 'Class_Globals'):  # Class_Globals imports the registry; excluding it avoids a cycle
        continue
    src = open(p, encoding='utf-8').read()
    if re.search(r'^export class ' + re.escape(base) + r'\b', src, re.M):
        names.append((base, os.path.relpath(p, game)[:-3].replace(os.sep, '/')))
out = ['// Generated by scripts/gen_classes.py. Do not edit by hand.']
out += ["import { %s } from './%s';" % (n, rel) for n, rel in names]
out += ['', 'export const classes = {'] + ['  %s,' % n for n, _ in names] + ['};', '', 'export type Classes = typeof classes;', '']
open(os.path.join(game, 'classes.ts'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
print(len(names), 'classes')
