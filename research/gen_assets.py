"""Generate src/game/**/Class_Assets*.ts from the decompiled Lingo asset classes (each in its folder, see
scripts/game_layout.py).

Each Lingo asset class is a list of `NAME = util.findMember("memberName", ASSET_CAST)` lines; precache()
only preloads, which the browser port does up front, so it becomes a no-op.

Usage: python -I research/gen_assets.py <decompiled Lingo dir> src/game
"""
import glob
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'scripts'))
from game_layout import folder_for  # noqa: E402

ASSIGN = re.compile(r'^\s+([A-Za-z0-9_]+) = util\.findMember\("([^"]*)"(?:, (ASSET_CAST|"[^"]*"))?\)\s*$')
CAST = re.compile(r'ASSET_CAST = "([^"]+)"')


def main(src_dir, out_dir):
    for path in sorted(glob.glob(os.path.join(src_dir, '*Class_Assets*.ls'))):
        cls = os.path.basename(path).split(' - ', 1)[1][:-3]
        text = open(path, encoding='utf-8').read()
        m = CAST.search(text)
        asset_cast = m.group(1) if m else None
        entries = []
        for line in text.splitlines():
            a = ASSIGN.match(line)
            if not a:
                continue
            prop, name, cast = a.groups()
            if cast == 'ASSET_CAST':
                cast = asset_cast
            elif cast:
                cast = cast.strip('"')
            entries.append((prop, name, cast))
        folder = folder_for(cls)
        up = '../' * (folder.count('/') + 1)
        util_path = os.path.relpath('core/Class_Utility', folder).replace(os.sep, '/')
        out = [
            '// Generated by research/gen_assets.py from the Lingo ' + cls + ' script. Do not edit by hand.',
            "import { Member } from '" + up + "../runtime';",
            "import { Class_Utility } from '" + (util_path if util_path.startswith('.') else './' + util_path) + "';",
            '',
            'export class ' + cls + ' {',
        ]
        for prop, _, _ in entries:
            out.append('  ' + prop + ': Member;')
        out += ['', '  constructor() {', '    this.locateMembers();', '  }', '', '  locateMembers(): void {',
                '    const util = new Class_Utility();']
        for prop, name, cast in entries:
            args = '"' + name + '"' + (', "' + cast + '"' if cast else '')
            out.append('    this.' + prop + ' = util.findMember(' + args + ');')
        out += ['  }', '',
                '  // Assets are loaded up front in the browser port.', '  precache(): void {}', '',
                '  // Lingo getaProp(#name): case-insensitive property lookup.',
                '  getaProp(name: string): Member | undefined {',
                "    const key = name.replace(/^#/, '').toLowerCase();",
                '    for (const k of Object.keys(this)) if (k.toLowerCase() === key) return (this as any)[k];',
                '    return undefined;', '  }', '}', '']
        os.makedirs(os.path.join(out_dir, folder), exist_ok=True)
        with open(os.path.join(out_dir, folder, cls + '.ts'), 'w', encoding='utf-8', newline='\n') as f:
            f.write('\n'.join(out))
        print(cls, len(entries), 'members, cast', asset_cast)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
